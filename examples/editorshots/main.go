// Command editorshots renders the Zed editor guide's samples and saves each one
// as a PNG. It is macOS-only; run it with make docs-editor-screenshots.
//
// The native backend used by this tool links GPL-3.0-or-later components.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/moriyoshi/gpui-go/editor"
)

// The functions below appear verbatim in docs/guide/editor.md.

const goSource = `package main

import "fmt"

func main() {
	fmt.Println("Hello from Go")
}
`

const prose = `Each editor owns its buffer, selection and undo history. This paragraph is long enough to reach the edge of the window, so soft wrapping has something to do when it is turned on.

Soft wrapping only changes how lines are shown. The text itself keeps its original line breaks.
`

const unicodeText = `日本語のテキスト
café, naïve, é
🦀 🐹 🚀
`

func OpenCode(ctx context.Context, app *editor.Client) (*editor.Editor, error) {
	return app.Open(ctx, editor.Options{
		Title:  "main.go",
		Text:   goSource,
		Width:  620,
		Height: 300,
	})
}

func OpenNotes(ctx context.Context, app *editor.Client) (*editor.Editor, error) {
	return app.Open(ctx, editor.Options{
		Title:      "Notes",
		Text:       prose,
		Width:      560,
		Height:     280,
		HideGutter: true,
	})
}

func OpenLog(ctx context.Context, app *editor.Client) (*editor.Editor, error) {
	return app.Open(ctx, editor.Options{
		Title:           "Build log",
		Text:            prose,
		Width:           560,
		Height:          280,
		ReadOnly:        true,
		DisableSoftWrap: true,
	})
}

func AddHeader(ctx context.Context, field *editor.Editor) (*editor.State, error) {
	return field.InsertText(ctx, "// Generated by Go\n")
}

// Mirror copies every edit in source to preview, in uppercase, until ctx ends.
func Mirror(ctx context.Context, app *editor.Client, source, preview *editor.Editor) error {
	for {
		event, err := app.NextEvent(ctx)
		if err != nil {
			return err
		}
		switch {
		case event.Kind == editor.Failed:
			return event.Error
		case event.Kind == editor.EditorClosed && event.EditorID == source.ID():
			return nil
		case event.Kind == editor.Changed && event.EditorID == source.ID():
			if _, err := preview.SetText(ctx, strings.ToUpper(event.State.Text)); err != nil {
				return err
			}
		}
	}
}

func GoToLine(ctx context.Context, field *editor.Editor, line uint32) (*editor.State, error) {
	caret := editor.Position{Line: line - 1}
	return field.SetSelection(ctx, caret, caret)
}

func SelectWord(ctx context.Context, field *editor.Editor) (*editor.State, error) {
	return field.SetSelection(ctx, editor.Position{Line: 119, Column: 5}, editor.Position{Line: 119, Column: 8})
}

// SaveOnChange writes each edit in field to path until the editor closes.
func SaveOnChange(ctx context.Context, app *editor.Client, field *editor.Editor, path string) error {
	for {
		event, err := app.NextEvent(ctx)
		if err != nil {
			return err
		}
		if event.EditorID != field.ID() {
			continue
		}
		switch event.Kind {
		case editor.Changed:
			if err := os.WriteFile(path, []byte(event.State.Text), 0o644); err != nil {
				return err
			}
		case editor.Failed:
			return event.Error
		case editor.EditorClosed:
			return nil
		}
	}
}

type capturer struct {
	out, windowIDs string
	settle         time.Duration
	seen           map[string]bool
}

func (c *capturer) windows(ctx context.Context) ([]string, error) {
	output, err := exec.CommandContext(ctx, c.windowIDs, strconv.Itoa(os.Getpid())).Output()
	if err != nil {
		return nil, fmt.Errorf("list windows: %w", err)
	}
	return strings.Fields(string(output)), nil
}

// capture saves the window this process opened since the last capture.
func (c *capturer) capture(ctx context.Context, name string) error {
	time.Sleep(c.settle)
	c.settle = 1500 * time.Millisecond
	path := filepath.Join(c.out, name+".png")
	lastErr := errors.New("no new window appeared")
	for range 30 {
		ids, err := c.windows(ctx)
		if err != nil {
			return err
		}
		for _, id := range ids {
			if c.seen[id] {
				continue
			}
			output, err := exec.CommandContext(ctx, "screencapture", "-x", "-o", "-l"+id, path).CombinedOutput()
			if err == nil {
				c.seen[id] = true
				log.Printf("captured %s", name)
				return nil
			}
			lastErr = fmt.Errorf("screencapture: %w: %s", err, output)
		}
		time.Sleep(500 * time.Millisecond)
	}
	return fmt.Errorf("%s: %w", name, lastErr)
}

// again allows the only open window to be captured a second time.
func (c *capturer) again(ctx context.Context) error {
	ids, err := c.windows(ctx)
	if err != nil {
		return err
	}
	for _, id := range ids {
		delete(c.seen, id)
	}
	return nil
}

func captureOpen(ctx context.Context, app *editor.Client, c *capturer) error {
	for _, item := range []struct {
		name string
		open func(context.Context, *editor.Client) (*editor.Editor, error)
	}{{"editor-code", OpenCode}, {"editor-notes", OpenNotes}, {"editor-log", OpenLog}} {
		field, err := item.open(ctx, app)
		if err != nil {
			return err
		}
		if err := c.capture(ctx, item.name); err != nil {
			return err
		}
		if err := field.Close(ctx); err != nil {
			return err
		}
	}

	unicode, err := app.Open(ctx, editor.Options{Title: "Unicode", Text: unicodeText, Width: 420, Height: 200})
	if err != nil {
		return err
	}
	if err := c.capture(ctx, "editor-unicode"); err != nil {
		return err
	}
	if err := unicode.Close(ctx); err != nil {
		return err
	}

	return nil
}

func captureUndo(ctx context.Context, app *editor.Client, c *capturer) error {
	field, err := OpenCode(ctx, app)
	if err != nil {
		return err
	}
	defer field.Close(ctx)
	if _, err := AddHeader(ctx, field); err != nil {
		return err
	}
	// A new window takes keyboard focus, so stray typing could reach the buffer
	// while waiting to capture. Read-only blocks it; the text is then verified.
	if err := expectStable(ctx, field, "// Generated by Go\n"+goSource); err != nil {
		return err
	}
	if err := c.capture(ctx, "editor-insert"); err != nil {
		return err
	}
	if _, err := field.SetReadOnly(ctx, false); err != nil {
		return err
	}
	if _, err := field.Undo(ctx); err != nil {
		return err
	}
	if err := expectStable(ctx, field, goSource); err != nil {
		return err
	}
	if err := c.again(ctx); err != nil {
		return err
	}
	return c.capture(ctx, "editor-undo")
}

// expectStable locks the buffer and checks that it holds exactly want.
func expectStable(ctx context.Context, field *editor.Editor, want string) error {
	state, err := field.SetReadOnly(ctx, true)
	if err != nil {
		return err
	}
	if state.Text != want {
		return fmt.Errorf("unexpected editor text: %q", state.Text)
	}
	return nil
}

func captureSelection(ctx context.Context, app *editor.Client, c *capturer) error {
	var numbered strings.Builder
	for i := 1; i <= 200; i++ {
		fmt.Fprintf(&numbered, "item %d\n", i)
	}
	field, err := app.Open(ctx, editor.Options{Title: "Items", Text: numbered.String(), Width: 420, Height: 240})
	if err != nil {
		return err
	}
	defer field.Close(ctx)
	if _, err := SelectWord(ctx, field); err != nil {
		return err
	}
	if err := expectStable(ctx, field, numbered.String()); err != nil {
		return err
	}
	state, err := field.State(ctx)
	if err != nil {
		return err
	}
	if want := (editor.Selection{Start: editor.Position{Line: 119, Column: 5}, End: editor.Position{Line: 119, Column: 8}}); state.Selection != want {
		return fmt.Errorf("selection: %+v", state.Selection)
	}
	return c.capture(ctx, "editor-selection")
}

func captureMirror(ctx context.Context, app *editor.Client, c *capturer) error {
	source, err := app.Open(ctx, editor.Options{Title: "Source", Width: 420, Height: 180})
	if err != nil {
		return err
	}
	if _, err := source.SetText(ctx, "Type here\nand it appears there\n"); err != nil {
		return err
	}
	if err := c.capture(ctx, "editor-mirror-source"); err != nil {
		return err
	}
	preview, err := app.Open(ctx, editor.Options{Title: "Preview", Width: 420, Height: 180, ReadOnly: true})
	if err != nil {
		return err
	}
	mirror, cancel := context.WithTimeout(ctx, 2*time.Second)
	defer cancel()
	if err := Mirror(mirror, app, source, preview); err != nil && !errors.Is(err, context.DeadlineExceeded) {
		return err
	}
	if err := c.capture(ctx, "editor-mirror-preview"); err != nil {
		return err
	}
	state, err := preview.State(ctx)
	if err != nil {
		return err
	}
	if state.Text != "TYPE HERE\nAND IT APPEARS THERE\n" {
		return fmt.Errorf("preview text: %q", state.Text)
	}
	return nil
}

func main() {
	out := flag.String("out", "docs/reference/screenshots", "directory for PNG files")
	windowIDs := flag.String("window-ids", "bin/docs-window-ids", "window listing helper built from tools/docs_window_ids.swift")
	only := flag.String("only", "", "capture only the group whose name contains this text: open, undo, selection or mirror")
	flag.Parse()
	err := editor.Run(context.Background(), func(ctx context.Context, app *editor.Client) error {
		// The first window compiles GPUI's shaders, so it needs longer to paint.
		c := &capturer{out: *out, windowIDs: *windowIDs, settle: 4 * time.Second, seen: map[string]bool{}}
		var failed error
		for _, group := range []struct {
			name string
			run  func(context.Context, *editor.Client, *capturer) error
		}{{"open", captureOpen}, {"undo", captureUndo}, {"selection", captureSelection}, {"mirror", captureMirror}} {
			if failed == nil && strings.Contains(group.name, *only) {
				failed = group.run(ctx, app, c)
			}
		}
		return errors.Join(failed, app.Quit(ctx))
	})
	if err != nil {
		log.Fatal(err)
	}
}
