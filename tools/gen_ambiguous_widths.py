#!/usr/bin/env python3
"""Writes rust/zed-editor/src/ambiguous.rs from Python's Unicode database.

Keep the Unicode version in step with the unicode-width crate.
"""
import sys
import unicodedata

UNICODE_VERSION = "16.0.0"

if unicodedata.unidata_version != UNICODE_VERSION:
    sys.exit(f"need Unicode {UNICODE_VERSION}, have {unicodedata.unidata_version}")

ranges = []
for code in range(0x110000):
    if unicodedata.east_asian_width(chr(code)) != "A":
        continue
    if ranges and ranges[-1][1] == code - 1:
        ranges[-1][1] = code
    else:
        ranges.append([code, code])

print(f"""//! East_Asian_Width=Ambiguous from Unicode {UNICODE_VERSION}.
//! Generated by tools/gen_ambiguous_widths.py. Do not edit.

const AMBIGUOUS: &[(char, char)] = &[""")
for start, end in ranges:
    print(f"    ('\\u{{{start:x}}}', '\\u{{{end:x}}}'),")
print("""];

pub(crate) fn is_ambiguous(c: char) -> bool {
    AMBIGUOUS
        .binary_search_by(|&(start, end)| {
            if c < start {
                std::cmp::Ordering::Greater
            } else if c > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ranges_are_sorted_and_disjoint() {
        assert!(AMBIGUOUS.iter().all(|&(start, end)| start <= end));
        assert!(AMBIGUOUS.windows(2).all(|pair| pair[0].1 < pair[1].0));
    }

    #[test]
    fn finds_the_edges_of_a_range() {
        assert!(is_ambiguous('\\u{a1}'));
        assert!(!is_ambiguous('\\u{a0}'));
        assert!(is_ambiguous('●'));
        assert!(!is_ambiguous('日'));
        assert!(!is_ambiguous('a'));
    }
}""")
