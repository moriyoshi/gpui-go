//go:build ignore

// gen writes one proxy file per entry of dist/native-targets.json, forwarding
// each dist/native-bindings.json function to that target's published module.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

type function struct {
	Name   string
	Params []string
	Result string
}

// Bao generates this export for every target, outside the binding manifest.
var tlsFinalize = function{Name: "TLSFinalizeCurrentThread"}

func goType(native string) string {
	if native == "pointer" {
		return "unsafe.Pointer"
	}
	return native
}

func proxy(fn function) string {
	var params, args []string
	for i, param := range fn.Params {
		params = append(params, fmt.Sprintf("a%d %s", i, goType(param)))
		args = append(args, fmt.Sprintf("a%d", i))
	}
	call := fmt.Sprintf("native.%s(%s)", fn.Name, strings.Join(args, ", "))
	if fn.Result != "" {
		return fmt.Sprintf("func %s(%s) %s { return %s }\n", fn.Name, strings.Join(params, ", "), goType(fn.Result), call)
	}
	return fmt.Sprintf("func %s(%s) { %s }\n", fn.Name, strings.Join(params, ", "), call)
}

func main() {
	out := flag.String("o", ".", "output directory")
	flag.Parse()
	log.SetFlags(0)
	var bindings struct{ Functions []function }
	var table struct {
		ModulePrefix string
		Targets      []struct{ Go string }
	}
	for path, value := range map[string]any{"../../dist/native-bindings.json": &bindings, "../../dist/native-targets.json": &table} {
		data, err := os.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		if err := json.Unmarshal(data, value); err != nil {
			log.Fatalf("%s: %v", path, err)
		}
	}
	for _, target := range table.Targets {
		goos, goarch, ok := strings.Cut(target.Go, "/")
		if !ok {
			log.Fatalf("invalid target %q", target.Go)
		}
		var source bytes.Buffer
		source.WriteString("// Code generated by gen.go from dist/native-bindings.json and dist/native-targets.json; DO NOT EDIT.\n\n")
		source.WriteString("//go:build gpui && gpui_prebuilt\n\npackage nativeshim\n\nimport (\n\t\"unsafe\"\n\n")
		fmt.Fprintf(&source, "\tnative %q\n)\n\n", table.ModulePrefix+"/"+goos+"-"+goarch)
		source.WriteString("var _ unsafe.Pointer\n\n")
		for _, fn := range append(bindings.Functions, tlsFinalize) {
			source.WriteString(proxy(fn))
		}
		formatted, err := format.Source(source.Bytes())
		if err != nil {
			log.Fatal(err)
		}
		name := filepath.Join(*out, fmt.Sprintf("prebuilt_%s_%s.go", goos, goarch))
		if err := os.WriteFile(name, formatted, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}
