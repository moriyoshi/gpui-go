//go:build ignore

// gen writes the prebuilt backend table from dist/native-bindings.json, and
// for each entry of dist/native-targets.json a package that registers that
// target's published module. The shim never imports a native module itself,
// so `go mod tidy` in a consumer only downloads the modules it imports.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

const header = "// Code generated by gen.go from dist/native-bindings.json and dist/native-targets.json; DO NOT EDIT.\n\n"

const umbrella = "github.com/moriyoshi/gpui-go"

type function struct {
	Name   string
	Params []string
	Result string
}

// Bao generates this export for every target, outside the binding manifest.
var tlsFinalize = function{Name: "TLSFinalizeCurrentThread"}

func goType(native string) string {
	if native == "pointer" {
		return "unsafe.Pointer"
	}
	return native
}

func signature(fn function) (params, args []string, result string) {
	for i, param := range fn.Params {
		params = append(params, fmt.Sprintf("a%d %s", i, goType(param)))
		args = append(args, fmt.Sprintf("a%d", i))
	}
	if fn.Result != "" {
		result = " " + goType(fn.Result)
	}
	return params, args, result
}

func write(path string, source []byte) {
	formatted, err := format.Source(source)
	if err != nil {
		log.Fatalf("%s: %v", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

func main() {
	out := flag.String("o", ".", "shim output directory")
	prebuilt := flag.String("prebuilt", "../../prebuilt", "registration package root")
	flag.Parse()
	log.SetFlags(0)
	var bindings struct{ Functions []function }
	var table struct {
		ModulePrefix string
		Targets      []struct{ Go string }
	}
	for path, value := range map[string]any{"../../dist/native-bindings.json": &bindings, "../../dist/native-targets.json": &table} {
		data, err := os.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		if err := json.Unmarshal(data, value); err != nil {
			log.Fatalf("%s: %v", path, err)
		}
	}
	functions := append(bindings.Functions, tlsFinalize)

	var backend bytes.Buffer
	backend.WriteString(header + "//go:build gpui_prebuilt\n\npackage nativeshim\n\nimport \"unsafe\"\n\nvar _ unsafe.Pointer\n\n")
	backend.WriteString("// Backend holds one published module's generated functions. Only the\n// packages under prebuilt/ construct it.\ntype Backend struct {\n")
	for _, fn := range functions {
		params, _, result := signature(fn)
		fmt.Fprintf(&backend, "\t%s func(%s)%s\n", fn.Name, strings.Join(params, ", "), result)
	}
	backend.WriteString("}\n\n")
	for _, fn := range functions {
		params, args, result := signature(fn)
		call := fmt.Sprintf("registered().%s(%s)", fn.Name, strings.Join(args, ", "))
		if result != "" {
			call = "return " + call
		}
		fmt.Fprintf(&backend, "func %s(%s)%s { %s }\n", fn.Name, strings.Join(params, ", "), result, call)
	}
	write(filepath.Join(*out, "prebuilt_backend.go"), backend.Bytes())

	var all bytes.Buffer
	for _, target := range table.Targets {
		goos, goarch, ok := strings.Cut(target.Go, "/")
		if !ok {
			log.Fatalf("invalid target %q", target.Go)
		}
		module := table.ModulePrefix + "/" + target.Go
		dir := filepath.Join(*prebuilt, goos, goarch)
		write(filepath.Join(dir, "doc.go"), []byte(fmt.Sprintf(header+
			"// Package %s registers the published %s native module. host imports it\n"+
			"// through package prebuilt under -tags gpui_prebuilt. On other\n"+
			"// platforms, or without those tags, it is empty.\npackage %s\n", goarch, target.Go, goarch)))
		var register bytes.Buffer
		fmt.Fprintf(&register, header+"//go:build gpui_prebuilt && %s && %s\n\npackage %s\n\n", goos, goarch, goarch)
		fmt.Fprintf(&register, "import (\n\t%q\n\n\tnative %q\n)\n\n", umbrella+"/internal/nativeshim", module)
		fmt.Fprintf(&register, "func init() {\n\tnativeshim.Register(%q, &nativeshim.Backend{\n", target.Go)
		for _, fn := range functions {
			fmt.Fprintf(&register, "\t\t%s: native.%s,\n", fn.Name, fn.Name)
		}
		register.WriteString("\t})\n}\n")
		write(filepath.Join(dir, "register.go"), register.Bytes())
		fmt.Fprintf(&all, "%s/prebuilt/%s\n", umbrella, target.Go)
	}

	var imports bytes.Buffer
	imports.WriteString(header + "//go:build gpui_prebuilt\n\npackage prebuilt\n\nimport (\n")
	for _, path := range strings.Fields(all.String()) {
		fmt.Fprintf(&imports, "\t_ %q\n", path)
	}
	imports.WriteString(")\n")
	write(filepath.Join(*prebuilt, "all.go"), imports.Bytes())
}
